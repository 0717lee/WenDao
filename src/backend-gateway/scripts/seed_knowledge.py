def main():
    print("=" * 60)
    print("营造法式知识库 V3 — 真实 Embedding 版")
    print("=" * 60)

    docs = build_knowledge_docs()
    print(f"\n共准备 {len(docs)} 条知识文档")

    # 按类别统计
    categories = {}
    for doc in docs:
        cat = doc.metadata.get("category", "unknown")
        categories[cat] = categories.get(cat, 0) + 1
    print("\n按类别统计：")
    for cat, count in sorted(categories.items()):
        print(f"  {cat}: {count} 条")

    # 初始化 Embedding
    cache_dir = os.path.join(os.path.dirname(__file__), "..", ".embedding_cache")
    embeddings = WenDaoEmbeddings(cache_dir=cache_dir)

    db_path = os.path.join(os.path.dirname(__file__), "..", "faiss_db")
    os.makedirs(db_path, exist_ok=True)

    print(f"\n正在将 {len(docs)} 条知识向量化并构建 FAISS 索引...")
    print(f"  Embedding 后端: {embeddings._active_backend}")

    vectorstore = FAISS.from_documents(documents=docs, embedding=embeddings)

    # FAISS C++ 层不支持含中文的 Windows 路径，改用字节序列化 + Python IO
    import pickle, faiss, numpy as np
    faiss_bytes = faiss.serialize_index(vectorstore.index)
    with open(os.path.join(db_path, "index.faiss"), "wb") as f:
        f.write(np.array(faiss_bytes).tobytes())
    with open(os.path.join(db_path, "index.pkl"), "wb") as f:
        pickle.dump((vectorstore.docstore, vectorstore.index_to_docstore_id), f)

    print(f"\n{'=' * 60}")
    print(f"成功构建知识库！共 {len(docs)} 条文档")
    print(f"   FAISS 索引保存至: {db_path}")
    print(f"   Embedding 缓存目录: {cache_dir}")
    print(f"{'=' * 60}")


if __name__ == "__main__":
    main()
